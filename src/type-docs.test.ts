import { expect, test } from "bun:test";
import { actionDoc, actionNames } from "./type-docs.ts";

// The shape gen-types.ts writes.
const SOURCE = `// Generated by gen-types.ts.

/** Data tool - styles. */
export interface DataStyleTool {
  /** Short doc. */
  get_styles<T = unknown>(input?: {
    /** Nested doc. */
    query?: string;
  }, tool: {
    siteId: string;
  }): Promise<T>;
  /**
   * Longer doc.
   *
   * Access: write.
   */
  update_style<T = unknown>(input: {
    name: string;
  }): Promise<T>;
  remove_style<T = unknown>(input: { name: string }): Promise<T>;
}
`;

test("actionNames", () => expect(actionNames(SOURCE)).toEqual(["get_styles", "update_style", "remove_style"]));

test("one action with its doc and every parameter", () => {
  expect(actionDoc(SOURCE, "get_styles")).toBe(
    "  /** Short doc. */\n  get_styles<T = unknown>(input?: {\n    /** Nested doc. */\n    query?: string;\n  }, tool: {\n    siteId: string;\n  }): Promise<T>;",
  );
  expect(actionDoc(SOURCE, "update_style")).toStartWith("  /**\n   * Longer doc.");
  expect(actionDoc(SOURCE, "update_style")).toEndWith("  }): Promise<T>;");
  expect(actionDoc(SOURCE, "remove_style")).toBe("  remove_style<T = unknown>(input: { name: string }): Promise<T>;");
  expect(actionDoc(SOURCE, "missing")).toBeUndefined();
});
